function pick(): { lang: 'es' | 'en'; dict: Dict } {
  let lang = 'es'
  try {
    lang = (navigator.languages?.[0] ?? navigator.language ?? 'es').toLowerCase()
  } catch {
    /* sin navigator */
  }
  return lang.startsWith('es') ? { lang: 'es', dict: es } : { lang: 'en', dict: en }
}

const current = pick()
export const lang = current.lang

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = current.dict[key] ?? es[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}
